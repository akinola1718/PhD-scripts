%% ========================================================================
% F0AM DILUTION-LIFETIME SENSITIVITY ANALYSIS
% FINAL: 6 h, 12 h, 24 h, 48 h
%
% Los Angeles base case: 31 July 2019
%
% FINAL CONFIGURATION
% -------------------------------------------------------------------------
% Chemistry:
%   CB6r2_K(Met)
%   CB6r2_J(Met,0)
%   CB6r2_AllRxns
%
% jcorr = 0.5
% chemical integration step = 10 min
%
% Dilution:
%       6 h
%      12 h
%      24 h   <-- BASELINE
%      48 h
%
% kdil = 1/(tau_dil * 3600)
%
% Diurnal simulation:
%   Spin-up = 3 complete diel cycles (July 28-30, 2019)
%   Analysis = July 31, 2019; O3 hard-reset to 15 ppb at 00:00
%   Full modeled state is propagated hour-to-hour; prescribed NO/NO2/CO are
%   refreshed hourly and primary VOC basket is refreshed once at each day start.
%
% Hourly constraints:
%   NO
%   NO2
%   CO
%
% O3:
%   unconstrained
%
% VOC:
%   initialized from observed mixture and chemically evolved
%
% Reference state:
%   mean start-of-hour NOx and VOC during 08:00-18:00 LT
%   mean pressure and RH during 08:00-18:00 LT
%
% Isopleth:
%   31 x 31
%   VOC = 0-150 ppb
%   NOx = 0-50 ppb
%   T = 290, 295, 300, 305 K
%   trajectory = 08:00-18:00 LT
%   response = maximum modeled O3 during each trajectory
%
% Ridge:
%   evaluated along NOx at fixed VOC
%   positive -> negative dO3/dNOx crossing
%   d2O3/dNOx2 < 0
%   highest-O3 candidate retained if multiple maxima occur
%
% IMPORTANT TIME HANDLING
% -------------------------------------------------------------------------
% ModelOptions.TimeStamp is intentionally NOT supplied.
%
% The previous warning:
%
% "ModelOptions.TimeStamp and output Time are different lengths"
%
% was caused by assigning an external timestamp vector whose length did not
% necessarily equal the F0AM returned time vector.
%
% Solar timing is supplied explicitly through SZA.
%
% PeakTime_LT is reconstructed from the ACTUAL number of returned O3
% concentrations across the known 08:00-18:00 integration interval.
%
% ========================================================================

