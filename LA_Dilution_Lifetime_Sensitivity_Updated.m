% HELPER FUNCTION 7
% SET TOTAL NOx WHILE PRESERVING NO:NO2 FRACTION
% ========================================================================

function InitConc2 = ...
    set_NOx_sum( ...
    InitConc1, ...
    NOx_sum)

    InitConc2 = ...
        InitConc1;

    iNO = ...
        find( ...
        strcmpi( ...
        InitConc1(:,1), ...
        'NO'), ...
        1);

    iNO2 = ...
        find( ...
        strcmpi( ...
        InitConc1(:,1), ...
        'NO2'), ...
        1);

    assert( ...
        ~isempty(iNO) && ...
        ~isempty(iNO2), ...
        'NO or NO2 missing.');

    NOv = InitConc1{iNO,2};
    NO2v = InitConc1{iNO2,2};

    total = NOv + NO2v;

    if ~isfinite(total) || total<=0

        fracNO = 0.5;

    else

        fracNO = ...
            NOv/total;

    end

    InitConc2{iNO,2} = ...
        NOx_sum*fracNO;

    InitConc2{iNO2,2} = ...
        NOx_sum*(1-fracNO);

end

