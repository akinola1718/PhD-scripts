    InitConc_iso_base = ...
        AnalysisStartStates{9};

    assert( ...
        ~isempty(InitConc_iso_base), ...
        '08:00 analysis-day chemical state was not stored.');

    InitConc_iso_base = ...
        set_NOx_sum( ...
        InitConc_iso_base, ...
        base_NOx);

    InitConc_iso_base = ...
        set_VOC_basket_sum( ...
        InitConc_iso_base, ...
        base_VOC, ...
        voc_species);

    %% ====================================================================
