                0);

        end

    end

end

%% ========================================================================
% HELPER FUNCTION 9
% RUN COMPLETE 31 x 31 ISOPLETH
%
% Maximum O3 is calculated from each actual returned F0AM trajectory.
%
% Peak time is reconstructed from the ACTUAL returned O3 length.
% ========================================================================

function [ ...
    o3_values, ...
    peak_times, ...
    end_slopes, ...
    peak_at_end ...
    ] = run_isopleth_grid_maxO3( ...
    Met_day, ...
    InitConc_base, ...
    ChemFiles, ...
    BkgdConc, ...
    ModelOptions, ...
    fNOx_grid, ...
    fVOC_grid, ...
    voc_species, ...
    start_hour, ...
    end_hour)

    num_runs = ...
        numel(fNOx_grid);

    assert( ...
        numel(fVOC_grid)==num_runs, ...
        'VOC and NOx grids have incompatible dimensions.');

    o3_values = ...
        nan(num_runs,1);

    peak_times = ...
        nan(num_runs,1);

    end_slopes = ...
        nan(num_runs,1);

    peak_at_end = ...
        false(num_runs,1);

    for i = 1:num_runs

        InitConc = ...
            InitConc_base;

        fnox = ...
            fNOx_grid(i);

        fvoc = ...
            fVOC_grid(i);

        %% ---------------------------------------------------------------
        % NO scaling
        % ---------------------------------------------------------------

        iNO = ...
            find( ...
            strcmpi( ...
            InitConc(:,1), ...
            'NO'), ...
            1);

        if ~isempty(iNO)

            InitConc{iNO,2} = ...
                max( ...
                InitConc{iNO,2}*fnox, ...
                0);

        end

        %% ---------------------------------------------------------------
        % NO2 scaling
        % ---------------------------------------------------------------

        iNO2 = ...
            find( ...
            strcmpi( ...
            InitConc(:,1), ...
            'NO2'), ...
            1);

        if ~isempty(iNO2)

            InitConc{iNO2,2} = ...
                max( ...
                InitConc{iNO2,2}*fnox, ...
                0);

        end

        %% ---------------------------------------------------------------
        % VOC scaling
        % ---------------------------------------------------------------

        for v = 1:numel(voc_species)

            idx = ...
                find( ...
                strcmpi( ...
                InitConc(:,1), ...
                voc_species{v}), ...
                1);

            if isempty(idx)
                continue;
            end

            InitConc{idx,2} = ...
                max( ...
                InitConc{idx,2}*fvoc, ...
                0);

        end

        %% ---------------------------------------------------------------
        % Run F0AM
        % ---------------------------------------------------------------

        S = ...
            F0AM_ModelCore( ...
            Met_day, ...
            InitConc, ...
            ChemFiles, ...
            BkgdConc, ...
            ModelOptions);

        %% ---------------------------------------------------------------
        % Extract actual returned O3
        % ---------------------------------------------------------------

        O3 = ...
            extract_species_series( ...
            S, ...
            'O3');

        if isempty(O3) || ...
                all(~isfinite(O3))

            continue;

        end

        O3 = O3(:);

        valid_idx = ...
            find(isfinite(O3));

        if isempty(valid_idx)
            continue;
        end

        %% ---------------------------------------------------------------
        % Maximum O3
        % ---------------------------------------------------------------

        [o3max_local,relative_index] = ...
            max( ...
            O3(valid_idx));

        imax = ...
            valid_idx(relative_index);

        o3_values(i) = ...
            o3max_local;

        %% ---------------------------------------------------------------
        % Reconstruct local-time coordinate from ACTUAL returned length
        %
        % This avoids assuming that F0AM output has the same length as
        % the externally supplied forcing vectors.
        % ---------------------------------------------------------------

        nO3 = ...
            numel(O3);

        if nO3>=2

            model_time = ...
                linspace( ...
                start_hour, ...
                end_hour, ...
                nO3)';

            peak_times(i) = ...
                model_time(imax);

            dt_actual = ...
                model_time(end) - ...
                model_time(end-1);

            if dt_actual>0 && ...
                    isfinite(O3(end)) && ...
                    isfinite(O3(end-1))

                end_slopes(i) = ...
                    ( ...
                    O3(end) - ...
                    O3(end-1) ...
                    ) / dt_actual;

            end

        elseif nO3==1

            peak_times(i) = ...
                start_hour;

        end

        %% ---------------------------------------------------------------
        % Temporal-boundary diagnostic
        % ---------------------------------------------------------------

        peak_at_end(i) = ...
            (imax==nO3);

    end

end

%% ========================================================================
% HELPER FUNCTION 10
% CORRECTED RIDGE EXTRACTION
%
% At fixed VOC:
%   O3 vs NOx
%
% Candidate ridge:
%   dO3/dNOx positive -> negative
%   d2O3/dNOx2 < 0
%
% If multiple:
%   highest modeled O3 retained.
%
% Boundary behavior is diagnosed independently.
% ========================================================================

function [RidgeTbl,BoundaryTbl] = ...
    detect_corrected_ridge( ...
    VOC_levels, ...
    NOx_levels, ...
    O3grid)

    ridgeVOC = [];
    ridgeNOx = [];
    ridgeO3 = [];
    ridgeRatio = [];

    nVOC = ...
        numel(VOC_levels);

    BoundaryVOC = ...
        nan(nVOC,1);

    dUpper = ...
        nan(nVOC,1);

    StillIncreasing = ...
        false(nVOC,1);

    BoundaryDominates = ...
        false(nVOC,1);

    NeedsLarger = ...
        false(nVOC,1);

    for j = 1:nVOC

        VOC = ...
            VOC_levels(j);

        x = ...
            NOx_levels(:);

        y = ...
            O3grid(j,:)';

        BoundaryVOC(j) = ...
            VOC;

        valid = ...
            isfinite(x) & ...
            isfinite(y);

        if sum(valid)<3
            continue;
        end

        xv = x(valid);
        yv = y(valid);

        d1 = ...
            gradient(yv,xv);

        d2 = ...
            gradient(d1,xv);

        dUpper(j) = ...
            d1(end);

        StillIncreasing(j) = ...
            isfinite(d1(end)) && ...
            d1(end)>0;

        candidates = [];

        for k = 1:(numel(xv)-1)

            if ~isfinite(d1(k)) || ...
                    ~isfinite(d1(k+1))

                continue;

            end

            if d1(k)>0 && ...
                    d1(k+1)<=0

                denom = ...
                    d1(k)-d1(k+1);

                if abs(denom)<eps
                    continue;
                end

                frac = ...
                    d1(k)/denom;

                xCross = ...
                    xv(k) + ...
                    frac*(xv(k+1)-xv(k));

                d2Cross = ...
                    interp1( ...
                    xv, ...
                    d2, ...
                    xCross, ...
                    'linear');

                O3Cross = ...
                    interp1( ...
                    xv, ...
                    yv, ...
                    xCross, ...
                    'linear');

                if isfinite(d2Cross) && ...
                        d2Cross<0 && ...
                        isfinite(O3Cross)

                    candidates = [
                        candidates
                        xCross O3Cross d2Cross
                        ]; %#ok<AGROW>

                end

            end

        end

        if ~isempty(candidates)

            [~,best] = ...
                max(candidates(:,2));

            bestNOx = ...
                candidates(best,1);

            bestO3 = ...
                candidates(best,2);

            ridgeVOC(end+1,1) = ...
                VOC; %#ok<AGROW>

            ridgeNOx(end+1,1) = ...
                bestNOx; %#ok<AGROW>

            ridgeO3(end+1,1) = ...
                bestO3; %#ok<AGROW>

            if bestNOx>0

                ridgeRatio(end+1,1) = ...
                    VOC/bestNOx; %#ok<AGROW>

            else

                ridgeRatio(end+1,1) = ...
                    NaN; %#ok<AGROW>

            end

            BoundaryDominates(j) = ...
                isfinite(yv(end)) && ...
                yv(end)>=bestO3;

        else

            if numel(yv)>1

                BoundaryDominates(j) = ...
                    isfinite(yv(end)) && ...
                    yv(end)>= ...
                    max( ...
                    yv(1:end-1), ...
                    [], ...
                    'omitnan');

            end

        end

        NeedsLarger(j) = ...
            StillIncreasing(j) || ...
            BoundaryDominates(j);

    end

    RidgeTbl = ...
        table( ...
        ridgeVOC, ...
        ridgeNOx, ...
        ridgeO3, ...
        ridgeRatio, ...
        'VariableNames',{ ...
        'VOC_ppb', ...
        'RidgeNOx_ppb', ...
        'RidgeO3_ppb', ...
        'VOC_NOx_Ratio'});

    BoundaryTbl = ...
        table( ...
        BoundaryVOC, ...
        dUpper, ...
        StillIncreasing, ...
        BoundaryDominates, ...
        NeedsLarger, ...
        'VariableNames',{ ...
        'VOC_ppb', ...
        'dO3dNOx_at_UpperBoundary', ...
        'UpperBoundary_StillIncreasing', ...
        'UpperBoundary_O3_DominatesInterior', ...
        'Needs_Larger_NOx_Domain'});

end

%% ========================================================================
% HELPER FUNCTION 11
% MODEL PERFORMANCE
% ========================================================================

function [MB,NMB,RMSE,NRMSE] = ...
    calculate_performance_stats( ...
    model_values, ...
    obs_values)

    model_values = ...
        model_values(:);

    obs_values = ...
        obs_values(:);

    valid = ...
        isfinite(model_values) & ...
        isfinite(obs_values);

    m = ...
        model_values(valid);

    o = ...
        obs_values(valid);

    if isempty(m)

        MB = NaN;
        NMB = NaN;
        RMSE = NaN;
        NRMSE = NaN;

        return;

    end

    MB = ...
        mean( ...
        m-o, ...
        'omitnan');

    obs_sum = ...
        sum( ...
        o, ...
        'omitnan');

    if abs(obs_sum)>eps

        NMB = ...
            100 .* ...
            sum( ...
            m-o, ...
            'omitnan') ./ ...
            obs_sum;

    else

        NMB = NaN;

    end

    RMSE = ...
        sqrt( ...
        mean( ...
        (m-o).^2, ...
        'omitnan'));

    mean_obs = ...
        mean( ...
        o, ...
        'omitnan');

    if abs(mean_obs)>eps

        NRMSE = ...
            100 .* ...
            RMSE ./ ...
            mean_obs;

    else

        NRMSE = NaN;

    end

end

