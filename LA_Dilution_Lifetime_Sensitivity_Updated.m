%% ========================================================================
% HELPER FUNCTION 2
% HOURLY SOLAR POSITION
%
% Critical correction:
% does NOT duplicate H+1 boundary.
% ========================================================================

function [time_blk,sun_blk] = ...
    hour_block_sun( ...
    run_date, ...
    UTC_offset, ...
    lat, ...
    lon, ...
    H, ...
    dt_minutes)

    t0 = ...
        run_date + hours(H);

    % Number of forcing points in one hour.
    nStep = ...
        60/dt_minutes;

    assert( ...
        abs(nStep-round(nStep))<1e-12, ...
        'dt_minutes must divide evenly into 60 minutes.');

    nStep = ...
        round(nStep);

    t_local = ...
        t0 + ...
        minutes( ...
        (0:nStep-1).*dt_minutes);

    t_local = ...
        t_local(:);

    o = ...
        ones(size(t_local));

    time_blk = struct();

    time_blk.year = ...
        year(t_local).*o;

    time_blk.month = ...
        month(t_local).*o;

    time_blk.day = ...
        day(t_local).*o;

    time_blk.hour = ...
        hour(t_local);

    time_blk.min = ...
        minute(t_local);

    time_blk.sec = ...
        second(t_local);

    time_blk.UTC = ...
        UTC_offset.*o;

    location = struct();

    location.latitude = lat;
    location.longitude = lon;
    location.altitude = 90;

    sun_blk = ...
        sun_position( ...
        time_blk, ...
        location);

end

%% ========================================================================
% HELPER FUNCTION 3
% SUM NOx
% ========================================================================

function val = ...
    init_sum_NOx(InitConc)

    iNO = ...
        find( ...
        strcmpi( ...
        InitConc(:,1), ...
        'NO'), ...
        1);

    iNO2 = ...
        find( ...
        strcmpi( ...
        InitConc(:,1), ...
        'NO2'), ...
        1);

    if isempty(iNO) || isempty(iNO2)

        val = NaN;
        return;

    end

    NOv = InitConc{iNO,2};
    NO2v = InitConc{iNO2,2};

    if ~isnumeric(NOv) || ...
            ~isnumeric(NO2v) || ...
            ~isfinite(NOv) || ...
            ~isfinite(NO2v)

        val = NaN;
        return;

    end

    val = NOv + NO2v;

end

%% ========================================================================
% HELPER FUNCTION 4
% SUM VOC BASKET
% ========================================================================

function val = ...
    init_sum_VOC( ...
    InitConc, ...
    voc_list)

    val = 0;

    for k = 1:numel(voc_list)

        idx = ...
            find( ...
            strcmpi( ...
            InitConc(:,1), ...
            voc_list{k}), ...
            1);

        if isempty(idx)
            continue;
        end

        x = InitConc{idx,2};

        if isnumeric(x) && ...
                isscalar(x) && ...
                isfinite(x)

            val = val + x;

        end

    end

end

