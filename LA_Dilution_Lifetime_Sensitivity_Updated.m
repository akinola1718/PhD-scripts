% HELPER FUNCTION 6
% CARRY FINAL MODELED STATE FORWARD
% ========================================================================

function InitConc_next = ...
    last_state_to_init( ...
    S, ...
    InitConc_template)

    InitConc_next = ...
        InitConc_template;

    names = {};
    final_values = [];

    if isfield(S,'Conc') && ...
            istable(S.Conc)

        names = ...
            S.Conc.Properties.VariableNames;

        final_values = ...
            S.Conc{end,:};

    elseif isfield(S,'Conc') && ...
            isstruct(S.Conc)

        names = ...
            fieldnames(S.Conc);

        final_values = ...
            nan(numel(names),1);

        for ii = 1:numel(names)

            x = ...
                S.Conc.(names{ii});

            if ~isempty(x)

                final_values(ii) = ...
                    x(end);

            end

        end

    elseif isfield(S,'Conc') && ...
            isnumeric(S.Conc) && ...
            isfield(S,'Chem') && ...
            isfield(S.Chem,'AllSpc')

        names = ...
            S.Chem.AllSpc;

        final_values = ...
            S.Conc(end,:);

    else

        warning( ...
            'Unable to identify F0AM concentration format.');

        return;

    end

    for ii = 1:size(InitConc_next,1)

        species_name = ...
            InitConc_next{ii,1};

        idx = ...
            find( ...
            strcmpi( ...
            names, ...
            species_name), ...
            1);

        if isempty(idx)
            continue;
        end

        x = ...
            final_values(idx);

        if isnumeric(x) && ...
                isscalar(x) && ...
                isfinite(x)

            InitConc_next{ii,2} = ...
                max(x,0);

        end

    end

end

