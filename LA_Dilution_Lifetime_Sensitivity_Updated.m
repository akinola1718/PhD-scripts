    fprintf('ANALYSIS-DAY O3 PERFORMANCE\n');
    fprintf('------------------------------------------------------------\n');
    fprintf('MB    = %.4f ppb\n',MB);
    fprintf('NMB   = %.4f %%\n',NMB);
    fprintf('RMSE  = %.4f ppb\n',RMSE);
    fprintf('NRMSE = %.4f %%\n',NRMSE);
    fprintf('------------------------------------------------------------\n');

    %% ====================================================================
    % 19. SAVE DIURNAL OUTPUT
    % =====================================================================

    DiurnalTbl = table( ...
        (0:23)', ...
        O3obs24, ...
        O3_cycle2, ...
        NOx_start_cycle2, ...
        VOC_start_cycle2, ...
        repmat(tau_h,24,1), ...
        repmat(kdil_s,24,1), ...
        'VariableNames',{ ...
        'Hour', ...
        'ObservedO3_ppb', ...
        'ModeledO3_ppb', ...
        'StartHour_NOx_ppb', ...
        'StartHour_VOC_ppb', ...
        'DilutionLifetime_h', ...
        'kdil_s_1'});

    writetable( ...
        DiurnalTbl, ...
        fullfile( ...
        tau_folder, ...
        sprintf( ...
        '%s_Diurnal_tau_%02dh.csv', ...
        city_name,tau_h)));


    % Publication-quality individual diurnal comparison for this lifetime
    fdi=figure('Color','w','Units','inches','Position',[1 1 7.2 5.0]);
    ax=axes('Parent',fdi); hold(ax,'on');
    plot(ax,0:23,O3obs24,'ko-','LineWidth',2.2,'MarkerSize',6, ...
        'MarkerFaceColor','w','DisplayName','Observed');
    plot(ax,0:23,O3_cycle2,'o-','LineWidth',2.0,'MarkerSize',5, ...
        'MarkerFaceColor','w','DisplayName',sprintf('\\tau_{dil} = %d h',tau_h));
    xlabel(ax,'Local time (h)'); ylabel(ax,'O_3 (ppb)');
    title(ax,sprintf('Los Angeles O_3: \\tau_{dil} = %d h',tau_h),'FontWeight','bold');
    xlim(ax,[0 23]); xticks(ax,0:3:23); grid(ax,'on'); box(ax,'on');
    ax.FontName='Arial'; ax.FontSize=12; ax.LineWidth=1.1; ax.TickDir='out'; ax.Layer='top';
    legend(ax,'Location','best','Box','off');
    save_publication_figure(fdi,tau_folder,sprintf('%s_Diurnal_tau_%02dh',city_name,tau_h));
    close(fdi);

    %% ====================================================================
    % 20. DAYTIME REFERENCE STATE
    %
    % Hours:
    % 08,09,10,11,12,13,14,15,16,17,18
    % =====================================================================

    daytime_idx = ...
        (8:18)+1;

