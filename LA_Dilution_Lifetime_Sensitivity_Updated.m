        year(t_iso_forcing).*oiso;

    time_iso.month = ...
        month(t_iso_forcing).*oiso;

    time_iso.day = ...
        day(t_iso_forcing).*oiso;

    time_iso.hour = ...
        hour(t_iso_forcing);

    time_iso.min = ...
        minute(t_iso_forcing);

    time_iso.sec = ...
        second(t_iso_forcing);

    time_iso.UTC = ...
        UTC_offset.*oiso;

    iso_location = struct();

    iso_location.latitude = lat;
    iso_location.longitude = lon;
    iso_location.altitude = 90;

    sun_iso = ...
        sun_position( ...
        time_iso, ...
        iso_location);

    ModelOptions_iso = ...
        ModelOptions;

    ModelOptions_iso.EndPointsOnly = 0;

    % Again: NO TimeStamp assignment.

