    ax=axes('Parent',fconv); hold(ax,'on');
    for jd=1:nSpinDays
        plot(ax,0:23,O3_spin_days(:,jd),'LineWidth',2.0,'DisplayName',datestr(spinup_dates(jd),'mmm dd'));
    end
    xlabel(ax,'Hour (LT)'); ylabel(ax,'Modeled O_3 (ppb)');
    title(ax,sprintf('Spin-up Convergence: \\tau_{dil} = %d h',tau_h),'FontWeight','bold');
    xlim(ax,[0 23]); xticks(ax,0:3:23); grid(ax,'on'); box(ax,'on');
    ax.FontName='Arial'; ax.FontSize=12; ax.LineWidth=1.1; ax.TickDir='out';
    legend(ax,'Location','southeast','Box','off');
    save_publication_figure(fconv,tau_folder,sprintf('%s_Spinup_Convergence_tau_%02dh',city_name,tau_h));
    close(fconv);

    % Continuous 3-day spin-up + analysis trajectory
    fcont=figure('Color','w','Units','inches','Position',[1 1 10.0 5.2]);
    ax=axes('Parent',fcont); hold(ax,'on');
    tSpin=[]; ySpin=[];
    for jd=1:nSpinDays
        tSpin=[tSpin; spinup_dates(jd)+hours((0:23)')]; %#ok<AGROW>
        ySpin=[ySpin; O3_spin_days(:,jd)]; %#ok<AGROW>
    end
    tAna=run_date+hours((0:23)');
    plot(ax,tSpin,ySpin,'LineWidth',2.0,'DisplayName','Modeled O_3');
    plot(ax,tAna,O3_cycle2,'LineWidth',2.0,'HandleVisibility','off');
    plot(ax,tAna,O3obs24,'o-','LineWidth',1.8,'MarkerSize',5,'MarkerFaceColor','w','DisplayName','Observed O_3 - July 31');
    for jd=2:nSpinDays
        xline(ax,spinup_dates(jd),'--','LineWidth',1.0,'HandleVisibility','off');
    end
    xline(ax,run_date,'--','LineWidth',1.0,'HandleVisibility','off');
    xlabel(ax,'Local Date and Time'); ylabel(ax,'O_3 (ppb)');
    title(ax,sprintf('Los Angeles: Continuous Spin-up and Analysis, \\tau_{dil} = %d h',tau_h),'FontWeight','bold');
    grid(ax,'on'); box(ax,'on'); ax.FontName='Arial'; ax.FontSize=11; ax.LineWidth=1.0; ax.TickDir='out';
    legend(ax,'Location','northwest');
    save_publication_figure(fcont,tau_folder,sprintf('%s_Continuous_Spinup_Analysis_tau_%02dh',city_name,tau_h));
    close(fcont);

    %% ====================================================================
    % 18. PERFORMANCE STATISTICS
