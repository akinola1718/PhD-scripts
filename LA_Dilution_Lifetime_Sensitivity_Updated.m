%% ========================================================================
% 15. MASTER DILUTION LOOP
% ========================================================================

for idil = 1:nTau

    tau_h = ...
        tau_dil_hours(idil);

    kdil_s = ...
        kdil_values(idil);

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('DILUTION LIFETIME = %d h\n',tau_h);
    fprintf('kdil = %.8e s^-1\n',kdil_s);
    fprintf('============================================================\n');

    tau_folder = ...
        fullfile( ...
        OutputDIR, ...
        sprintf('tau_%02dh',tau_h));

    if ~exist(tau_folder,'dir')
        mkdir(tau_folder);
    end

    %% ====================================================================
    % 16. THREE-DAY SPIN-UP + JULY 31 ANALYSIS
    % =====================================================================

    InitConc_now = InitConc_base;
    O3_spin_days = nan(24,nSpinDays);
    O3_cycle2 = nan(24,1);
    NOx_start_cycle2 = nan(24,1);
    VOC_start_cycle2 = nan(24,1);
    AnalysisStartStates = cell(24,1);

    % ------------------------- SPIN-UP DAYS -------------------------------
    for iday = 1:nSpinDays
        this_date = spinup_dates(iday);
        fprintf('Running spin-up day %d/%d: %s\n',iday,nSpinDays,datestr(this_date,'mmm dd'));

        % Reinitialize only the prescribed primary VOC basket once per day.
        % All other modeled species retain the propagated chemical state.
        InitConc_now = reset_primary_vocs(InitConc_now,InitConc_base,voc_species);

        for H = 0:23
            [time_blk,sun_blk] = hour_block_sun(this_date,UTC_offset,lat,lon,H,dt_minutes);
            Met_blk = {
                'P', P24(H+1).*ones(size(time_blk.hour))
                'T', Temp24(H+1).*ones(size(time_blk.hour))
                'RH',RH24(H+1).*ones(size(time_blk.hour))
                'SZA',sun_blk.zenith
                'jcorr',jcorr
                'kdil',kdil_s};

            % Same hourly primary constraints used by the base case.
            InitConc_now = set_species_value(InitConc_now,'NO', NO24(H+1));
            InitConc_now = set_species_value(InitConc_now,'NO2',NO224(H+1));
            InitConc_now = set_species_value(InitConc_now,'CO', CO24(H+1));

            Sblk = F0AM_ModelCore(Met_blk,InitConc_now,ChemFiles,BkgdConc,ModelOptions);
            O3_blk = extract_species_series(Sblk,'O3');
            if isempty(O3_blk) || all(~isfinite(O3_blk))
                O3_spin_days(H+1,iday)=NaN;
            else
                O3_spin_days(H+1,iday)=mean(O3_blk,'omitnan');
            end
            InitConc_now = last_state_to_init(Sblk,InitConc_now);
        end
    end

    % ------------------------- ANALYSIS DAY -------------------------------
    fprintf('Running retained analysis day: July 31, 2019\n');

    % Daily VOC initialization, identical in concept to spin-up days.
    InitConc_now = reset_primary_vocs(InitConc_now,InitConc_base,voc_species);

    % Required base-case analysis-day O3 reset.
    InitConc_now = set_species_value(InitConc_now,'O3',15.00);

    for H = 0:23
        [time_blk,sun_blk] = hour_block_sun(run_date,UTC_offset,lat,lon,H,dt_minutes);
        Met_blk = {
            'P', P24(H+1).*ones(size(time_blk.hour))
            'T', Temp24(H+1).*ones(size(time_blk.hour))
            'RH',RH24(H+1).*ones(size(time_blk.hour))
            'SZA',sun_blk.zenith
            'jcorr',jcorr
            'kdil',kdil_s};

        InitConc_now = set_species_value(InitConc_now,'NO', NO24(H+1));
        InitConc_now = set_species_value(InitConc_now,'NO2',NO224(H+1));
        InitConc_now = set_species_value(InitConc_now,'CO', CO24(H+1));

        AnalysisStartStates{H+1}=InitConc_now;
        NOx_start_cycle2(H+1)=init_sum_NOx(InitConc_now);
        VOC_start_cycle2(H+1)=init_sum_VOC(InitConc_now,voc_species);

        Sblk=F0AM_ModelCore(Met_blk,InitConc_now,ChemFiles,BkgdConc,ModelOptions);
        O3_blk=extract_species_series(Sblk,'O3');
        if isempty(O3_blk) || all(~isfinite(O3_blk))
            O3_cycle2(H+1)=NaN;
        else
            O3_cycle2(H+1)=mean(O3_blk,'omitnan');
        end
        InitConc_now=last_state_to_init(Sblk,InitConc_now);
    end

    O3_all_dilution(:,idil)=O3_cycle2;
    O3_analysis_all(:,idil)=O3_cycle2;
    O3_spinup_all(:,:,idil)=O3_spin_days;

    %% ====================================================================
    % 17. SPIN-UP DIAGNOSTIC + PER-TAU FIGURES
    % =====================================================================
    SpinupTbl = table((0:23)',O3_spin_days(:,1),O3_spin_days(:,2),O3_spin_days(:,3), ...
        'VariableNames',{'Hour','SpinDay1_O3_ppb','SpinDay2_O3_ppb','SpinDay3_O3_ppb'});
    writetable(SpinupTbl,fullfile(tau_folder,sprintf('%s_Spinup_Diagnostic_tau_%02dh.csv',city_name,tau_h)));

