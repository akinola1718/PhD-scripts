% HELPER FUNCTION 5
% EXTRACT F0AM SPECIES SERIES
% ========================================================================

function series = ...
    extract_species_series( ...
    S, ...
    species_name)

    series = [];

    if ~isfield(S,'Conc')
        return;
    end

    if istable(S.Conc)

        vars = ...
            S.Conc.Properties.VariableNames;

        idx = ...
            find( ...
            strcmpi( ...
            vars, ...
            species_name), ...
            1);

        if ~isempty(idx)

            series = ...
                S.Conc{:,idx};

        end

    elseif isstruct(S.Conc)

        f = ...
            fieldnames(S.Conc);

        idx = ...
            find( ...
            strcmpi( ...
            f, ...
            species_name), ...
            1);

        if ~isempty(idx)

            series = ...
                S.Conc.(f{idx});

        end

    elseif isnumeric(S.Conc) && ...
            isfield(S,'Chem') && ...
            isfield(S.Chem,'AllSpc')

        idx = ...
            find( ...
            strcmpi( ...
            S.Chem.AllSpc, ...
            species_name), ...
            1);

        if ~isempty(idx)

            series = ...
                S.Conc(:,idx);

        end

    end

    if ~isempty(series)
        series = series(:);
    end

end

