    VOC_base_all(idil) = ...
        base_VOC;

    fprintf('\n');
    fprintf('08:00-18:00 REFERENCE STATE\n');
    fprintf('------------------------------------------------------------\n');
    fprintf('NOx = %.6f ppb\n',base_NOx);
    fprintf('VOC = %.6f ppb\n',base_VOC);
